//! The v0.10.35 option-struct layouts.
//!
//! `src/sys/bindings.rs` is generated from MediaPipe master, where `BaseOptions`
//! carries a `file_descriptor` field that v0.10.35 does not have. That single
//! insertion is the *only* layout difference between the two versions across
//! every header this crate binds — results, landmarks, categories, rects,
//! keypoints, matrices and images are byte-identical, and every other change in
//! `v0.10.35..master` is a pure rename. So the compatibility surface is exactly
//! the structs below, used only at the two `*Create` call sites.
//!
//! ```text
//! offset   v0.10.35 (56 bytes)          master (72 bytes)
//!      0   model_asset_buffer           model_asset_buffer
//!      8   model_asset_buffer_count     model_asset_buffer_count   (+4 pad)
//!     16   model_asset_path             model_asset_path
//!     24   delegate                     file_descriptor   <-- inserted
//!     28   host_environment             delegate
//!     32   host_system      (+4 pad)    host_environment
//!     36   -                            host_system
//!     40   host_version                 host_version
//!     48   ca_bundle_path               ca_bundle_path
//!     56   -                            app_id
//!     64   -                            app_version
//! ```
//!
//! Getting this wrong does not crash: the C side reads `running_mode` from the
//! wrong offset and reports `kMpInvalidArgument: Unsupported running mode:
//! unknown mode`. [`crate::Error`] annotates that message with an ABI hint.

use super::bindings::{
    MpDelegate, MpFaceDetectorOptions_result_callback_fn,
    MpFaceLandmarkerOptions_result_callback_fn, MpHostEnvironment, MpHostSystem, MpRunningMode,
};
use std::os::raw::{c_char, c_int, c_uint};

/// `BaseOptions` as laid out by v0.10.35 — no `file_descriptor`, no `app_*`.
#[repr(C)]
#[derive(Debug, Clone, Copy)]
pub struct MpBaseOptionsV35 {
    pub model_asset_buffer: *const c_char,
    pub model_asset_buffer_count: c_uint,
    pub model_asset_path: *const c_char,
    pub delegate: MpDelegate,
    pub host_environment: MpHostEnvironment,
    pub host_system: MpHostSystem,
    pub host_version: *const c_char,
    pub ca_bundle_path: *const c_char,
}

impl MpBaseOptionsV35 {
    /// Zeroed except for the model source and delegate, which is all this crate sets.
    pub fn new(
        model_asset_buffer: *const c_char,
        model_asset_buffer_count: c_uint,
        model_asset_path: *const c_char,
        delegate: MpDelegate,
    ) -> Self {
        Self {
            model_asset_buffer,
            model_asset_buffer_count,
            model_asset_path,
            delegate,
            host_environment: MpHostEnvironment::MP_HOST_ENVIRONMENT_UNKNOWN,
            host_system: MpHostSystem::MP_HOST_SYSTEM_UNKNOWN,
            host_version: std::ptr::null(),
            ca_bundle_path: std::ptr::null(),
        }
    }
}

#[repr(C)]
#[derive(Debug, Clone, Copy)]
pub struct MpFaceDetectorOptionsV35 {
    pub base_options: MpBaseOptionsV35,
    pub running_mode: MpRunningMode,
    pub min_detection_confidence: f32,
    pub min_suppression_threshold: f32,
    pub result_callback: MpFaceDetectorOptions_result_callback_fn,
}

#[repr(C)]
#[derive(Debug, Clone, Copy)]
pub struct MpFaceLandmarkerOptionsV35 {
    pub base_options: MpBaseOptionsV35,
    pub running_mode: MpRunningMode,
    pub num_faces: c_int,
    pub min_face_detection_confidence: f32,
    pub min_face_presence_confidence: f32,
    pub min_tracking_confidence: f32,
    pub output_face_blendshapes: bool,
    pub output_facial_transformation_matrixes: bool,
    pub result_callback: MpFaceLandmarkerOptions_result_callback_fn,
}

// The whole shim is worthless if these drift. bindings.rs carries the same
// assertions for the master layouts, generated by bindgen from the headers.
const _: () = assert!(size_of::<MpBaseOptionsV35>() == 56);
const _: () = assert!(size_of::<super::MpBaseOptions>() == 72);
const _: () = assert!(std::mem::offset_of!(MpBaseOptionsV35, delegate) == 24);
const _: () = assert!(std::mem::offset_of!(super::MpBaseOptions, delegate) == 28);
const _: () = assert!(size_of::<MpFaceDetectorOptionsV35>() == 80);
const _: () = assert!(size_of::<super::MpFaceDetectorOptions>() == 96);
const _: () = assert!(size_of::<MpFaceLandmarkerOptionsV35>() == 88);
const _: () = assert!(size_of::<super::MpFaceLandmarkerOptions>() == 104);
const _: () = assert!(std::mem::offset_of!(MpFaceDetectorOptionsV35, running_mode) == 56);
const _: () = assert!(std::mem::offset_of!(super::MpFaceDetectorOptions, running_mode) == 72);
